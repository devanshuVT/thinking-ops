#!/usr/bin/env python3
"""Validate board files and regenerate BOARD.md. Stdlib only."""
import sys, pathlib, datetime, json
ROOT = pathlib.Path(__file__).resolve().parent.parent
AGENT_STATUS = ["queued", "running", "blocked", "done"]
IDEA_STATUS = ["open", "promoted", "dropped"]
TASK_STATUS = ["draft", "ready", "in_progress", "review", "done"]
PROJECT_STATUS = ["active", "paused", "done"]
PROJECT_FIELDS = ("name", "path", "repo", "goal", "status", "area", "next", "linked_agents", "linked_ideas")

def parse(path):
    t = path.read_text().split("\n")
    if not t or t[0].strip() != "---":
        raise ValueError("missing frontmatter")
    d, i = {}, 1
    while i < len(t) and t[i].strip() != "---":
        if ":" in t[i]:
            k, v = t[i].split(":", 1)
            d[k.strip()] = v.strip().strip('"')
        i += 1
    if i >= len(t):
        raise ValueError("unterminated frontmatter")
    d["_body"] = "\n".join(t[i + 1:]).strip()
    d["_id"] = path.stem
    return d

def load(folder):
    out, errs = [], []
    for p in sorted((ROOT / folder).glob("*.md")):
        try:
            out.append(parse(p))
        except Exception as e:
            errs.append(f"{p.relative_to(ROOT)}: {e}")
    return out, errs

def num(v, lo, hi, label, errs, ident):
    try:
        n = float(v)
    except Exception:
        errs.append(f"{ident}: {label} must be a number"); return lo
    if not lo <= n <= hi:
        errs.append(f"{ident}: {label} must be {lo}-{hi}")
    return n

def main():
    agents, e1 = load("board/agents"); ideas, e2 = load("board/ideas"); tasks, e3 = load("tasks")
    projects, e4 = load("board/projects")
    errs = e1 + e2 + e3 + e4
    for a in agents:
        if a.get("status") not in AGENT_STATUS: errs.append(f"{a['_id']}: bad status")
        if a.get("status") == "blocked" and not a.get("blocker"): errs.append(f"{a['_id']}: blocked needs a blocker")
        num(a.get("progress", 0), 0, 100, "progress", errs, a["_id"])
    for i in ideas:
        if i.get("status") not in IDEA_STATUS: errs.append(f"{i['_id']}: bad status")
        for k in ("impact", "confidence", "effort"): num(i.get(k, 0), 1, 5, k, errs, i["_id"])
    for t in tasks:
        if t.get("status") not in TASK_STATUS: errs.append(f"{t['_id']}: bad status")
    agent_ids = {a["_id"] for a in agents}
    idea_ids = {i["_id"] for i in ideas}
    for p in projects:
        for k in PROJECT_FIELDS:
            if k not in p: errs.append(f"{p['_id']}: missing {k}")
        for k in ("name", "goal"):
            if not p.get(k): errs.append(f"{p['_id']}: {k} required")
        if p.get("status") not in PROJECT_STATUS: errs.append(f"{p['_id']}: bad status")
        for k, ids in (("linked_agents", agent_ids), ("linked_ideas", idea_ids)):
            for linked_id in [v.strip() for v in p.get(k, "").split(",") if v.strip()]:
                if linked_id not in ids: errs.append(f"{p['_id']}: unknown {k} id {linked_id}")
    if errs:
        print("VALIDATION FAILED"); [print(" -", e) for e in errs]; sys.exit(1)

    score = lambda i: round(float(i["impact"]) * float(i["confidence"]) / max(1.0, float(i["effort"])), 1)
    by = {s: [a for a in agents if a["status"] == s] for s in AGENT_STATUS}
    open_ideas = sorted([i for i in ideas if i["status"] == "open"], key=score, reverse=True)
    ready = [t for t in tasks if t["status"] == "ready"]
    review = [t for t in tasks if t["status"] == "review"]
    L = ["# Agent board", "", "_Generated by `scripts/board.py`. Do not edit._", "",
         f"**Running** {len(by['running'])} · **Blocked** {len(by['blocked'])} · **Queued** {len(by['queued'])} · "
         f"**Done** {len(by['done'])} · **Open ideas** {len(open_ideas)} · **Tasks ready** {len(ready)} · **Awaiting your review** {len(review)}", ""]
    if len(by["running"]) > 3: L += [f"> Warning: {len(by['running'])} agents running, above the cap of 3.", ""]
    L += ["## Needs you", ""]
    needs = [f"- **{a['name']}** (blocked): {a['blocker']}" for a in by["blocked"]] + \
            [f"- **{t['title']}** (task in review, agent: {t.get('agent','-')})" for t in review]
    L += needs or ["Nothing waiting on you."]
    L += ["", "## Projects", "", "| Project | Status | Area | Goal | Path | Next | Linked agents | Linked ideas |",
          "|---|---|---|---|---|---|---|---|"]
    for p in projects:
        L.append(f"| {p['name']} | {p['status']} | {p.get('area','')} | {p['goal']} | {p.get('path','')} | {p.get('next','')} | {p.get('linked_agents','')} | {p.get('linked_ideas','')} |")
    L += ["", "## Agents", "", "| Agent | Status | Progress | Next | Owner |", "|---|---|---|---|---|"]
    for s in ["running", "blocked", "queued", "done"]:
        for a in by[s]: L.append(f"| {a['name']} | {s} | {a.get('progress','0')}% | {a.get('next','')} | {a.get('owner','')} |")
    L += ["", "## Idea ranking (impact × confidence ÷ effort)", "", "| Idea | Area | I | C | E | Score |", "|---|---|---|---|---|---|"]
    for i in open_ideas: L.append(f"| {i['title']} | {i.get('area','')} | {i['impact']} | {i['confidence']} | {i['effort']} | {score(i)} |")
    L += ["", "## Task queue", "", "| Task | Status | Assignee | Agent |", "|---|---|---|---|"]
    for t in tasks:
        if t["status"] != "done": L.append(f"| {t['title']} | {t['status']} | {t.get('assignee','')} | {t.get('agent','')} |")
    (ROOT / "BOARD.md").write_text("\n".join(L) + "\n")
    clean = lambda d: {k: v for k, v in d.items() if not k.startswith("_")} | {"id": d["_id"]}
    decisions = [{"id": p.stem, "title": (p.read_text().splitlines() or [""])[0].lstrip("# ").strip()} for p in sorted((ROOT / "decisions").glob("*.md"))]
    data = {"generated": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
            "agents": [clean(a) for a in agents],
            "ideas": [clean(i) | {"score": score(i)} for i in ideas],
            "tasks": [clean(t) for t in tasks], "decisions": decisions,
            "projects": [clean(p) for p in projects]}
    (ROOT / "site").mkdir(exist_ok=True)
    (ROOT / "site" / "data.json").write_text(json.dumps(data, indent=1) + "\n")
    print(f"ok: {len(agents)} agents, {len(ideas)} ideas, {len(tasks)} tasks, {len(projects)} projects")

if __name__ == "__main__": main()
